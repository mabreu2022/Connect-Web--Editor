const db = require('./firebird');

async function initStoreDb() {
  console.log('[DB-INIT] Inicializando tabelas da loja de componentes no Firebird...');

  try {
    // 1. Verificar/Criar TB_COMPONENTS
    const hasComponentsTable = await checkTableExists('TB_COMPONENTS');
    if (!hasComponentsTable) {
      console.log('[DB-INIT] Criando tabela TB_COMPONENTS...');
      await db.execute(`
        CREATE TABLE TB_COMPONENTS (
          COM_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          COM_TITLE VARCHAR(255) NOT NULL,
          COM_DESCRIPTION VARCHAR(1000),
          COM_CATEGORY VARCHAR(100) NOT NULL,
          COM_PRICE DECIMAL(10,2) NOT NULL,
          COM_THUMBNAIL_URL VARCHAR(1000),
          COM_PAYLOAD BLOB SUB_TYPE TEXT NOT NULL
        )
      `);
      console.log('[DB-INIT] Tabela TB_COMPONENTS criada com sucesso!');
    }

    // 2. Verificar/Criar TB_ORDERS
    const hasOrdersTable = await checkTableExists('TB_ORDERS');
    if (!hasOrdersTable) {
      console.log('[DB-INIT] Criando tabela TB_ORDERS...');
      await db.execute(`
        CREATE TABLE TB_ORDERS (
          ORD_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          ORD_USU_ID INTEGER NOT NULL,
          ORD_COM_ID INTEGER NOT NULL,
          ORD_STATUS VARCHAR(20) DEFAULT 'pending' NOT NULL,
          ORD_COMPROVANTE BLOB SUB_TYPE TEXT,
          ORD_CRIADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          ORD_ATUALIZ TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
      `);
      console.log('[DB-INIT] Tabela TB_ORDERS criada com sucesso!');
    }

    // 3. Verificar/Criar TB_USER_COMPONENTS
    const hasUserComponentsTable = await checkTableExists('TB_USER_COMPONENTS');
    if (!hasUserComponentsTable) {
      console.log('[DB-INIT] Criando tabela TB_USER_COMPONENTS...');
      await db.execute(`
        CREATE TABLE TB_USER_COMPONENTS (
          USC_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          USC_USU_ID INTEGER NOT NULL,
          USC_COM_ID INTEGER NOT NULL,
          USC_CONCEDIDO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          CONSTRAINT UNQ_USC_USU_COM UNIQUE (USC_USU_ID, USC_COM_ID)
        )
      `);
      console.log('[DB-INIT] Tabela TB_USER_COMPONENTS criada com sucesso!');
    }

    // 4. Inserir componentes padrão se a tabela estiver vazia
    const countResult = await db.query('SELECT COUNT(*) AS TOTAL FROM TB_COMPONENTS');
    const totalComponents = countResult[0]?.total || 0;
    if (totalComponents === 0) {
      console.log('[DB-INIT] Populando componentes padrão na loja...');
      await populateDefaultComponents();
    }

  } catch (err) {
    console.error('[DB-INIT] Erro durante a inicialização das tabelas da loja:', err);
  }
}

async function checkTableExists(tableName) {
  try {
    const result = await db.query(
      `SELECT RDB$RELATION_NAME FROM RDB$RELATIONS WHERE TRIM(RDB$RELATION_NAME) = ?`,
      [tableName.toUpperCase()]
    );
    return result.length > 0;
  } catch (err) {
    return false;
  }
}

